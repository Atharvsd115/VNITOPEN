// Helper to generate normalized 24-hr activity array
const genHourly = (peakStart: number, peakEnd: number, baseLevel: number = 20): number[] => {
  return Array.from({ length: 24 }, (_, hour) => {
    if (hour < 5 || hour > 23) return Math.floor(Math.random() * 5);
    if (hour >= peakStart && hour <= peakEnd) {
      return Math.min(100, Math.floor(75 + Math.random() * 25));
    }
    const dist = Math.min(Math.abs(hour - peakStart), Math.abs(hour - peakEnd));
    return Math.max(10, Math.floor(baseLevel + Math.max(0, 60 - dist * 14) + Math.random() * 10));
  });
};

const genWeekly = (baseTrx: number) => {
  const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  return days.map((day, idx) => {
    const multiplier = idx >= 5 ? 1.4 : (idx === 4 ? 1.2 : 0.95 + Math.random() * 0.15);
    const transactions = Math.round(baseTrx * multiplier);
    return {
      day,
      transactions,
      footfall: Math.round(transactions * 1.85)
    };
  });
};

